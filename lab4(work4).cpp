#include <Wire.h>               // Підключаємо базову бібліотеку для роботи з шиною I2C
#include <OneWire.h>            // Підключаємо бібліотеку для роботи з протоколом 1-Wire
#include <DallasTemperature.h>  // Підключаємо бібліотеку для температурного сенсора DS18B20
#include <Adafruit_Sensor.h>    // Підключаємо базовий клас універсальних сенсорів від Adafruit
#include <Adafruit_BMP280.h>    // Підключаємо бібліотеку для роботи з барометром BMP280
#include "SPIFFS.h"             // Підключаємо бібліотеку файлової системи для флеш-пам'яті ESP32

 // ************************************* АПАРАТНІ НАЛАШТУВАННЯ ***************************************
const uint8_t PIN_TEMP_DQ = 4;        // Вказуємо цифровий GPIO пін 4 для лінії даних DS18B20
const uint8_t PIN_LIGHT_ADC = 34;     // Вказуємо аналоговий пін 34 для зчитування напруги з фоторезистора

// ************************************* ІНІЦІАЛІЗАЦІЯ ОБ'ЄКТІВ ***************************************
OneWire oneWireInterface(PIN_TEMP_DQ);           // Створюємо об'єкт шини 1-Wire на вказаному піні
DallasTemperature ds18b20(&oneWireInterface);    // Передаємо шину об'єкту сенсора DS18B20
Adafruit_BMP280 bmp280Sensor;                    // Створюємо об'єкт для барометра BMP280 (I2C за замовчуванням)

// ************************************* НАЛАШТУВАННЯ ТАЙМЕРА ТА ФАЙЛІВ *******************************
unsigned long previousRecordTime = 0;            // Змінна для зберігання часу останнього запису даних
const unsigned long RECORD_INTERVAL_MS = 5000;   // Інтервал між вимірами: 5000 мілісекунд (5 секунд)

const char* CSV_FILE_PATH = "/lab_data.csv";     // Задаємо шлях та ім'я файлу у пам'яті (обов'язково з '/')

// ************************************* ФУНКЦІЯ ЗАПИСУ ДАНИХ *****************************************
// Функція опитує сенсори, формує CSV-рядок і дописує його у файл
void recordDataToStorage(unsigned long currentTimestamp) {
    ds18b20.requestTemperatures();                           // Надсилаємо команду DS18B20 виміряти температуру
    float dsTemperature = ds18b20.getTempCByIndex(0);        // Зчитуємо результат у градусах Цельсія

    float bmpTemperature = bmp280Sensor.readTemperature();   // Зчитуємо температуру з барометра BMP280
    float bmpPressure = bmp280Sensor.readPressure() / 100.0F;// Зчитуємо тиск (переводимо з Паскалів у гектопаскалі - hPa)
    int lightAdcValue = analogRead(PIN_LIGHT_ADC);           // Зчитуємо сире значення АЦП (від 0 до 4095) з фоторезистора

    // Формуємо рядок даних у форматі CSV (Comma-Separated Values). Використовуємо 2 знаки після коми для float
    String logEntry = String(currentTimestamp) + "," +       // Додаємо мітку часу та кому
        String(dsTemperature, 2) + "," +       // Додаємо температуру DS18B20 та кому
        String(bmpTemperature, 2) + "," +      // Додаємо температуру BMP280 та кому
        String(bmpPressure, 2) + "," +         // Додаємо тиск та кому
        String(lightAdcValue) + "\r\n";        // Додаємо рівень світла та символи перенесення каретки (новий рядок)

    // Відкриваємо файл у режимі "a" (append - дописування в кінець файлу)
    File dataFile = SPIFFS.open(CSV_FILE_PATH, "a");

    if (dataFile) {                                          // Якщо файл успішно відкрито
        dataFile.print(logEntry);                            // Записуємо сформований рядок у флеш-пам'ять
        dataFile.close();                                    // Обов'язково закриваємо файл для збереження змін
        Serial.print("[ІК-31] Збережено: " + logEntry);      // Виводимо підтвердження у консоль
    }
    else {
        Serial.println("[ПОМИЛКА] Не вдалося відкрити файл для запису!"); // Повідомляємо, якщо пам'ять недоступна
    }
}

// ************************************* ФУНКЦІЯ ЧИТАННЯ ФАЙЛУ ****************************************
// Функція відкриває файл, читає його побайтово і виводить у Serial Monitor
void outputStorageContent() {
    Serial.println("\n===== ДРУК ВМІСТУ ФАЙЛУ З ПАМ'ЯТІ =====");

    // Відкриваємо файл у режимі "r" (read - лише читання)
    File dataFile = SPIFFS.open(CSV_FILE_PATH, "r");

    if (!dataFile) {                                         // Якщо файлу не існує або він пошкоджений
        Serial.println("[ПОМИЛКА] Файл відсутній або не може бути прочитаний.");
        return;                                              // Перериваємо виконання функції
    }

    Serial.print("Загальний розмір файлу (байт): ");         // Виводимо інформаційне повідомлення
    Serial.println(dataFile.size());                         // Виводимо фактичний розмір файлу на диску

    // Читаємо файл, поки є доступні байти
    while (dataFile.available()) {
        Serial.write(dataFile.read());                       // Зчитуємо один символ і відправляємо його в консоль
    }

    dataFile.close();                                        // Закриваємо файл після завершення читання
    Serial.println("=======================================\n");
}

// ************************************* ГОЛОВНИЙ БЛОК НАЛАШТУВАННЯ ***********************************
void setup() {
    Serial.begin(115200);                                    // Запускаємо серійний порт на швидкості 115200 бод
    delay(1000);                                             // Чекаємо 1 секунду для стабілізації живлення плати

    Serial.println("\n[ІК-31] Ініціалізація системи...");

    // --- Ініціалізація датчиків ---
    ds18b20.begin();                                         // Запускаємо драйвер 1-Wire для DS18B20

    if (!bmp280Sensor.begin(0x76)) {                         // Пробуємо знайти BMP280 за адресою I2C 0x76
        Serial.println("[ПОМИЛКА] Барометр BMP280 не знайдено! Перевірте контакти.");
    }
    else {
        Serial.println("Сенсори підключено успішно.");
    }

    // --- Ініціалізація файлової системи SPIFFS ---
    // Аргумент true означає: "Якщо файлової системи ще немає, відформатувати пам'ять"
    if (!SPIFFS.begin(true)) {
        Serial.println("[КРИТИЧНА ПОМИЛКА] Збій монтування SPIFFS розділу.");
        return;                                              // Зупиняємо подальше виконання у разі збою
    }
    Serial.println("Пам'ять SPIFFS змонтовано успішно.");

    // --- Створення або перезапис файлу ---
    // Відкриваємо файл у режимі "w" (write - створити новий або повністю очистити існуючий)
    File dataFile = SPIFFS.open(CSV_FILE_PATH, "w");
    if (dataFile) {
        // Записуємо перший рядок (шапку таблиці CSV)
        dataFile.print("Timestamp_ms,Temp_DS_C,Temp_BMP_C,Pressure_hPa,Light_ADC\r\n");
        dataFile.close();                                    // Закриваємо файл
        Serial.println("Файл даних створено/очищено. Шапку таблиці записано.");
    }
}

// ************************************* ГОЛОВНИЙ ЦИКЛ ************************************************
void loop() {
    unsigned long currentMillis = millis();                  // Отримуємо поточний час роботи мікроконтролера

    // --- БЛОК 1: ЗБІР ТА ЗАПИС ДАНИХ (працює по таймеру) ---
    // Перевіряємо, чи пройшло достатньо часу (5000 мс) з моменту останнього запису
    if (currentMillis - previousRecordTime >= RECORD_INTERVAL_MS) {
        previousRecordTime = currentMillis;                  // Оновлюємо мітку часу
        recordDataToStorage(currentMillis);                  // Викликаємо функцію збору та запису на диск
    }

    // --- БЛОК 2: ОБРОБКА КОМАНД КОРИСТУВАЧА ---
    // Перевіряємо, чи надійшли якісь символи з комп'ютера у Serial Monitor
    if (Serial.available() > 0) {
        String incomingCommand = Serial.readStringUntil('\n'); // Читаємо весь рядок до символу Enter
        incomingCommand.trim();                              // Видаляємо зайві пробіли та невидимі символи по краях

        // Якщо користувач написав слово "read"
        if (incomingCommand == "read") {
            outputStorageContent();                          // Викликаємо функцію для виводу всього файлу в консоль
        }
    }
}