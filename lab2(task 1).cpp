// Визначаємо піни константами, щоб не витрачати пам'ять
const int SENSOR_LDR_PIN = 4;  // Вхід для фоторезистора (читаємо напругу через АЦП)
const int LED_DAC_PIN = 25;    // Вихід на світлодіод (керуємо напругою через ЦАП)

void setup() {
	// Запускаємо монітор порту для виводу даних
	Serial.begin(115200);
}

void loop() {
	// 1. АЦП (Аналого-цифрове перетворення)
	// ESP32 має 12-бітний АЦП, тому значення освітленості буде від 0 до 4095
	int rawLightValue = analogRead(SENSOR_LDR_PIN);

	// 2. Адаптація значень для ЦАП
	// ЦАП (Цифро-аналоговий перетворювач) у ESP32 8-бітний, приймає від 0 до 255.
	// Функція map() пропорційно переносить діапазон АЦП у діапазон ЦАП.
	// Зверніть увагу: я інвертую значення (255 до 0), щоб при меншому світлі діод світив яскравіше.
	int outputVoltageLevel = map(rawLightValue, 0, 4095, 255, 0);

	// Функція constrain гарантує, що значення точно не вийде за межі 0-255 (захист від помилок)
	outputVoltageLevel = constrain(outputVoltageLevel, 0, 255);

	// 3. ЦАП (керування світлодіодом)
	dacWrite(LED_DAC_PIN, outputVoltageLevel);

	// Вивід результатів для аналізу
	Serial.print("[INFO] Рівень освітленості (АЦП): ");
	Serial.print(rawLightValue);
	Serial.print(" | Значення на діоді (ЦАП): ");
	Serial.println(outputVoltageLevel);

	delay(100); // Невелика затримка для стабільності роботи
}

