#include <OneWire.h>           // Підключення бібліотеки для роботи з протоколом 1-Wire
#include <DallasTemperature.h> // Підключення бібліотеки для керування температурним датчиком DS18B20

 // ************************************* АПАРАТНІ НАЛАШТУВАННЯ ***************************************
const uint8_t PIN_DS18B20 = 4;        // Цифровий пін ESP32, до якого підключено шину даних сенсора
const int SAMPLES_COUNT = 10;         // Кількість вимірів для збору (згідно твого початкового коду)
const int READ_DELAY_MS = 1000;       // Інтервал між вимірюваннями у мілісекундах (1 секунда)

// ************************************* ІНІЦІАЛІЗАЦІЯ ОБ'ЄКТІВ ***************************************
OneWire oneWireInterface(PIN_DS18B20);           // Ініціалізація шини 1-Wire на вказаному піні
DallasTemperature dsSensor(&oneWireInterface);   // Передача об'єкта шини до головного класу сенсора

// ************************************* ГЛОБАЛЬНІ МАСИВИ ********************************************
float rawSensorValues[SAMPLES_COUNT];            // Масив для збереження "сирих" вимірів температури
float kalmanFilteredValues[SAMPLES_COUNT];       // Масив для збереження математично відфільтрованих результатів

// ********************************* ПАРАМЕТРИ ФІЛЬТРА КАЛЬМАНА **************************************
// Константи та змінні для налаштування математичної моделі фільтра (1D Kalman Filter)
float previousEstimate = 0.0;       // Змінна для зберігання попередньої обчисленої оцінки температури
float errorCovariance = 1.0;        // Початкове значення коваріації (дисперсії) похибки
const float PROCESS_NOISE = 0.022;  // Q: Дисперсія шуму самого процесу (швидкість зміни реального середовища)
const float MEASURE_NOISE = 0.617;  // R: Дисперсія шуму вимірювання (апаратна похибка самого датчика DS18B20)

// ********************************* ФУНКЦІЯ ФІЛЬТРАЦІЇ **********************************************
// Виносимо логіку фільтра в окрему функцію для кращої структурованості коду
void processKalmanFilter() {
    // Ініціалізуємо базову оцінку першим реально виміряним значенням з масиву
    previousEstimate = rawSensorValues[0];

    // Виводимо шапку таблиці для результатів
    Serial.println("Сирі дані (°C)\tВідфільтровані (°C)\tПохибка (Різниця)");
    Serial.println("---------------------------------------------------------");

    // Проходимо циклом по всьому масиву зібраних температур
    for (int i = 0; i < SAMPLES_COUNT; i++) {
        float currentMeasurement = rawSensorValues[i]; // Беремо поточне "сире" значення з масиву на цій ітерації

        // --- ЕТАП 1: ПРОГНОЗУВАННЯ (Prediction Phase) ---
        float predictedState = previousEstimate;                   // Прогнозуємо, що температура лишилась такою ж
        float predictedErrorCov = errorCovariance + PROCESS_NOISE; // Збільшуємо невизначеність на величину шуму середовища

        // --- ЕТАП 2: КОРЕКЦІЯ (Update Phase) ---
        // Обчислюємо коефіцієнт підсилення Кальмана (Kalman Gain) - наскільки довіряємо датчику
        float kalmanGain = predictedErrorCov / (predictedErrorCov + MEASURE_NOISE);

        // Вираховуємо фінальну оцінку: коригуємо прогноз з урахуванням нового фактичного виміру
        float currentEstimate = predictedState + kalmanGain * (currentMeasurement - predictedState);

        // Оновлюємо коваріацію похибки для використання у наступному кроці циклу
        float currentErrorCov = (1.0 - kalmanGain) * predictedErrorCov;

        // Зберігаємо вирахуване ідеальне значення у вихідний масив результатів
        kalmanFilteredValues[i] = currentEstimate;

        // Виводимо результати роботи алгоритму в консоль (з точністю до 3 знаків після коми)
        // Функція abs() повертає модуль числа (різницю без мінуса)
        Serial.printf("%.3f\t\t%.3f\t\t\t%.3f\n", currentMeasurement, currentEstimate, abs(currentMeasurement - currentEstimate));

        // Перезаписуємо глобальні змінні новими даними для наступної ітерації
        errorCovariance = currentErrorCov;
        previousEstimate = currentEstimate;
    }
}

// ************************************* ГОЛОВНИЙ БЛОК НАЛАШТУВАННЯ **********************************
void setup() {
    Serial.begin(115200);      // Ініціалізуємо серійний порт на швидкості 115200 бод (стандарт ESP32)
    dsSensor.begin();          // Запускаємо датчик температури на шині

    Serial.println("\n[ІК-31] Старт системи. Починаю збір значень з DS18B20...");

    // --- ЕТАП ЗБОРУ ДАНИХ ---
    for (int i = 0; i < SAMPLES_COUNT; i++) {
        dsSensor.requestTemperatures();                  // Відправляємо сенсору команду виконати вимір
        rawSensorValues[i] = dsSensor.getTempCByIndex(0);// Зчитуємо конвертовані дані з першого (індекс 0) сенсора

        // Форматований вивід: %02d додає нуль попереду для чисел до 10, %.2f залишає 2 знаки після коми
        Serial.printf("Зріз [%02d]: %.2f °C\n", (i + 1), rawSensorValues[i]);

        delay(READ_DELAY_MS); // Робимо апаратну затримку між вимірами
    }

    Serial.println("\n[ІК-31] Збір даних завершено. Запуск математичної моделі Кальмана...\n");

    // Викликаємо нашу створену функцію для обробки зібраного масиву
    processKalmanFilter();

    Serial.println("\n[ІК-31] Математичну обробку масиву успішно завершено.");
}

