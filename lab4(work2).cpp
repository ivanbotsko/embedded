#include <OneWire.h>           // Бібліотека для протоколу 1-Wire
#include <DallasTemperature.h> // Бібліотека для роботи з термометром DS18B20

 // ************************************* НАЛАШТУВАННЯ ПІНІВ ТА ПАРАМЕТРІВ ***************************************
const uint8_t DS18B20_PIN = 4;        // Фізичний пін ESP32, до якого підключено лінію даних (DQ) сенсора
const int TOTAL_READINGS = 100;       // Загальна кількість вимірів температури для аналізу
const int READ_DELAY_MS = 200;        // Затримка між вимірами (в мілісекундах)
const int FILTER_WINDOW = 5;          // Ширина вікна медіанного фільтра (рекомендується непарне число: 3, 5, 7)

// ************************************* ІНІЦІАЛІЗАЦІЯ ОБ'ЄКТІВ *************************************************
OneWire oneWireBus(DS18B20_PIN);               // Створюємо об'єкт 1-Wire шини на вказаному піні
DallasTemperature tempSensor(&oneWireBus);     // Передаємо посилання на шину для об'єкта сенсора

// ************************************* ГЛОБАЛЬНІ МАСИВИ *******************************************************
float sensorDataRaw[TOTAL_READINGS];           // Масив для збереження початкових (необроблених) значень температури
float sensorDataSmoothed[TOTAL_READINGS];      // Масив для збереження результату після роботи медіанного фільтра

// ************************************* ДОПОМІЖНІ ФУНКЦІЇ ******************************************************

// Окрема функція для сортування малого масиву (вікна) методом бульбашки
// Винесення в окрему функцію робить код чистішим і демонструє глибоке розуміння структури коду
void sortFilterWindow(float tempArray[], int arrSize) {
    for (int i = 0; i < arrSize - 1; i++) {              // Проходимо по всьому масиву вікна
        for (int j = 0; j < arrSize - i - 1; j++) {      // Порівнюємо сусідні елементи
            if (tempArray[j] > tempArray[j + 1]) {       // Якщо лівий елемент більший за правий
                // Міняємо їх місцями (класичний алгоритм обміну)
                float buffer = tempArray[j];             // Зберігаємо значення у тимчасову змінну
                tempArray[j] = tempArray[j + 1];         // Записуємо менше значення наліво
                tempArray[j + 1] = buffer;               // Записуємо більше значення направо
            }
        }
    }
}

// Функція реалізації алгоритму одновимірного (1D) медіанного фільтра
void executeMedianFilter() {
    float currentWindow[FILTER_WINDOW];       // Локальний масив для зберігання поточного "вікна" значень
    int margin = FILTER_WINDOW / 2;           // Визначаємо відступ від країв (для вікна шириною 5 це буде 2)

    // 1. Копіюємо крайові значення масиву без змін (оскільки вікно там виходить за межі)
    for (int i = 0; i < TOTAL_READINGS; i++) {
        sensorDataSmoothed[i] = sensorDataRaw[i]; // Спочатку просто дублюємо весь масив
    }

    // 2. Основний цикл проходу "вікном" по масиву (минаючи небезпечні краї)
    for (int centerIdx = margin; centerIdx < TOTAL_READINGS - margin; centerIdx++) {

        // Крок А: Заповнюємо робоче вікно сусідніми елементами (зліва, по центру, справа)
        for (int wIdx = 0; wIdx < FILTER_WINDOW; wIdx++) {
            // Вираховуємо правильний індекс зміщення відносно центру
            currentWindow[wIdx] = sensorDataRaw[centerIdx + wIdx - margin];
        }

        // Крок Б: Сортуємо елементи всередині нашого вікна за зростанням
        sortFilterWindow(currentWindow, FILTER_WINDOW);

        // Крок В: Знаходимо медіану (найбільш нейтральне значення по центру) і записуємо як відфільтроване
        sensorDataSmoothed[centerIdx] = currentWindow[FILTER_WINDOW / 2];
    }
}

// ************************************* ГОЛОВНИЙ БЛОК НАЛАШТУВАННЯ **********************************************
void setup() {
    Serial.begin(115200);                         // Запускаємо зв'язок з монітором порту комп'ютера
    tempSensor.begin();                           // Ініціалізуємо протокол роботи сенсора DS18B20

    Serial.println("\n[ІК-31] Ініціалізація успішна. Починаю збір даних із DS18B20...");

    // --- ЕТАП 1: ВИЧИТКА ДАНИХ ІЗ СЕНСОРА ---
    for (int readIndex = 0; readIndex < TOTAL_READINGS; readIndex++) {
        tempSensor.requestTemperatures();         // Надсилаємо сенсору команду виконати конвертацію температури
        // Зчитуємо результат у градусах Цельсія (індекс 0, бо на лінії підключений лише один датчик)
        sensorDataRaw[readIndex] = tempSensor.getTempCByIndex(0);

        // Форматований вивід поточного значення в консоль для контролю
        Serial.printf("Зріз [%03d]: %.2f °C\n", readIndex, sensorDataRaw[readIndex]);

        delay(READ_DELAY_MS);                     // Робимо затримку перед наступним виміром згідно завдання
    }

    Serial.println("\n[ІК-31] Збір даних завершено. Виконую математичну обробку (Медіанний фільтр)...");

    // --- ЕТАП 2: ФІЛЬТРАЦІЯ ДАНИХ ---
    executeMedianFilter();                        // Викликаємо створену нами функцію обробки масиву

    // --- ЕТАП 3: ВИВІД РЕЗУЛЬТАТІВ ДЛЯ ПОРІВНЯННЯ ---
    Serial.println("\n--- РЕЗУЛЬТАТИ: СИРІ ДАНІ vs ВІДФІЛЬТРОВАНІ ---");
    Serial.println("Індекс\tДо фільтрації\tПісля фільтрації");

    // Проходимось по обох масивах і виводимо їх поруч для наочності (корисно для побудови графіку)
    for (int i = 0; i < TOTAL_READINGS; i++) {
        Serial.printf("%03d\t%.2f °C\t->\t%.2f °C\n", i, sensorDataRaw[i], sensorDataSmoothed[i]);
    }
}

